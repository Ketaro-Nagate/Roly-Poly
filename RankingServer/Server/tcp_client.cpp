#include<stdio.h>
#include "tcp_client.h"

//==================================================================================
// コンストラクタ
//==================================================================================
CTcpClient::CTcpClient()
{
	m_Socket = INVALID_SOCKET;
}

//==================================================================================
// デストラクタ
//==================================================================================
CTcpClient::~CTcpClient()
{

}

//==================================================================================
// メイン
//==================================================================================
bool CTcpClient::Init(const char* pIPAddress, int nPortNum)
{
	//---------------//
	// ソケット作成
	//---------------//
	printf("[通信用のソケットを作成]\n");

	m_Socket = socket(AF_INET, SOCK_STREAM, 0);

	if (m_Socket == INVALID_SOCKET)
	{
		// ソケットの作成に失敗した場合
		printf("ソケットの作成に失敗\n");
		getchar();
		rewind(stdin);

		return 0;
	}

	//---------------//
	// 接続先の設定
	// 接続先のIPアドレスを入力	

	struct sockaddr_in addr;				// sockaddr_in　接続先を指定する構造体
	addr.sin_family = AF_INET;
	addr.sin_port = htons(22333);			// 接続先ポート番号
	addr.sin_addr.S_un.S_addr = inet_addr(pIPAddress);

	//----------------//
	// サーバーに接続
	//----------------//
	if (connect(m_Socket, (struct sockaddr*)&addr, sizeof(addr)) != 0)
	{
		printf("接続に失敗しました\n");
		getchar();
		rewind(stdin);

		return 0;
	}
}

//==================================================================================
// 初期化( オーバーロード )
//==================================================================================
bool CTcpClient::Init(SOCKET sock)
{
	// 接続済みソケットをメンバ変数に設定
	m_Socket = sock;

	if (m_Socket == NULL)
	{
		return false;
	}

	return true;
}

//==================================================================================
// 送信処理
//==================================================================================
int CTcpClient::Send(char* pSendData, int nSendDataSize)
{
	//--- 接続済みかチェック ---//
	if (m_Socket == INVALID_SOCKET)
	{
		return 0;
	}

	send(m_Socket, pSendData, nSendDataSize, 0);			// 接続先に送信

	return nSendDataSize;
}

//==================================================================================
// 受信処理
//==================================================================================
int CTcpClient::Recv(char* pRecvData, int nRecvDataSize)
{
	//--- 接続済みかチェック ---//
	if (m_Socket == INVALID_SOCKET)
	{
		return 0;
	}

	//----------------//
	// データの送受信
	//----------------//
	int nRecvByte = recv(m_Socket, pRecvData, nRecvDataSize, 0);
	// recv関数 : データを受信する	/  recv(ソケットディスクリプタ, 受信データ格納先, 格納先バイト数, フラグ)
	// recvを実行すると、データを受信するまで一時停止する
	// ※受信バイト数が０の場合、接続が切断されたことを示す

	//--- 接続が終了した場合、終了処理を実行 ---//
	if (nRecvByte <= 0)
	{
		Uninit();
	}

	return nRecvByte;
}

//==================================================================================
// 終了処理
//==================================================================================
void CTcpClient::Uninit(void)
{
	//--- 接続済みかチェック ---//
	if (m_Socket == INVALID_SOCKET)
	{
		return;
	}

	// サーバーとの接続を閉じる
	closesocket(m_Socket);

	m_Socket = INVALID_SOCKET;
}