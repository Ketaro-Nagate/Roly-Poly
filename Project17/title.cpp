//==================================================================================
// 初期化
//==================================================================================
HRESULT CTitle::Init(CScene::MODE mode)
{
	CObject::ReleaseAll();

	// テクスチャへのポインタ取得
	CManager* pManager = CManager::GetManager();
	CTexture* pTexture = CManager::GetManager()->GetTexture();

	// シーンクラスの初期化
	CScene::Init(mode);

	// タイトルロゴを生成
	m_pLogo = CObject2D::Create(D3DXVECTOR3(SCREEN_WIDTH * 0.5f, SCREEN_HEIGHT * 0.4f, 0.0f), 1280.0f, 720.0f);	// インスタンス生成
	m_pLogo->BindTexture(pTexture->GetAddress(CTexture::TEX_TITLE));				// テクスチャ割り当て

	return S_OK;
}

//==================================================================================
// 終了
//==================================================================================
void CTitle::Uninit(void)
{
	// オブジェクトを破棄
	CObject::ReleaseAll();

	// カメラリセット
	CManager::GetManager()->GetCamera()->ResetCamera();

	//--- テクスチャ破棄 ---//

#ifndef CSCENE_COBJECT
	CObject::Release();
#endif // !CSCENE_COBJECT
}

//==================================================================================
// 更新
//==================================================================================
void CTitle::Update(void)
{
	static bool Pause = false;

	CManager* pManager = CManager::GetManager();
	CInputKeyboard* pKey = pManager->GetInputKeyboard();

	// エンターで遷移
	if (pKey->GetTrigger(DIK_RETURN))
	{
		pManager->SetMode(MODE_GAME);
	}
	
}

