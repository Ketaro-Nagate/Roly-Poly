//==================================================================================
// 生成
//==================================================================================
CScene* CScene::Create(MODE mode)
{
	// インスタンス生成
	CScene* pScene = nullptr;

	// 指定されたモードシーンの生成
	switch (mode)
	{
	case MODE_TITLE:			// タイトルシーン生成
		pScene = new CTitle;
		break;

	case MODE_GAME:				// ゲームシーン生成
		pScene = new CGame;
		break;
	}

	// 初期化
	if (pScene != nullptr)
		pScene->Init(mode);

	// インスタンスのポインタを返す
	return pScene;
}

//==================================================================================
// 初期化
//==================================================================================
HRESULT CScene::Init(MODE mode)
{
	m_mode = mode;
	return S_OK;
}

