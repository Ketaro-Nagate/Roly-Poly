//**********************************************************************************
//	マクロ定義
//**********************************************************************************
#define SIZE (15.0f)			// 判定上サイズ

//==================================================================================
// コンストラクタ
//==================================================================================
CBallObject::CBallObject()
{
	m_pos = NULL_D3DXVECTOR3;		// 位置
	m_rot = NULL_D3DXVECTOR3;		// 角度
	m_fRadius = SIZE;
}

//==================================================================================
// デストラクタ
//==================================================================================
CBallObject::~CBallObject()
{
}

//==================================================================================
// 生成( 生成モデルのファイル指定 )
//==================================================================================
CBallObject* CBallObject::Create(D3DXVECTOR3 pos, D3DXVECTOR3 rot, float fRadius,const char* pFileName)
{
	// インスタンス生成
	CBallObject* pItem = new CBallObject;

	// 初期化
	pItem->Init(pos, rot, fRadius, pFileName);

	// ポインタをかえす
	return pItem;
}

//==================================================================================
// 初期化処理
//==================================================================================
HRESULT CBallObject::Init(void)
{
	return S_FALSE;
}

//==================================================================================
// 初期化処理
//==================================================================================
HRESULT CBallObject::Init(D3DXVECTOR3 pos, D3DXVECTOR3 rot, float fRadius, const char* pFileName)
{
	// Xモデルの初期化
	CObjectX::Init(pos, rot, pFileName);

	// 位置角度の保存
	m_pos = pos;
	m_rot = rot;
	m_fRadius = fRadius;

	return S_OK;
}

//==================================================================================
// 終了処理
//==================================================================================
void CBallObject::Uninit(void)
{
	CObjectX::Uninit();
}
//==================================================================================
// 更新処理
//==================================================================================
void CBallObject::Update(void)
{
	// プレイヤーを取得
	CManager* pManager = CManager::GetManager();
	CScene* pScene = pManager->GetScene();
	CPlayer* pPlayer = pScene->GetPlayer();

	// 当たり判定
	BallCollision(pPlayer->GetPPos(), pPlayer->GetRadius());
}

//==================================================================================
// 描画処理呼び出し
//==================================================================================
void CBallObject::Draw(void)
{
	CObjectX::Draw();
}

//==================================================================================
// 当たり判定(球)
//==================================================================================
bool CBallObject::BallCollision(D3DXVECTOR3* pos, float fRadius)
{
	D3DXVECTOR3 DPos = m_pos;		// 自身の位置
	D3DXVECTOR3 vecToPos = DPos - *pos;

	if (D3DXVec3Length(&vecToPos) <= (double)m_fRadius + (double)fRadius)
	{// 球判定・真
		D3DXVECTOR3 p = *pos - DPos;
		D3DXVec3Normalize(&p, &p);
		*pos = DPos + (p * (m_fRadius + fRadius));
		return true;
	}

	return false;
}