#include "main.h"
#include "effect.h"
#include "manager.h"
#include "input.h"

//==================================================================================
// コンストラクタ
//==================================================================================
CEffect::CEffect()
{
	m_move = NULL_D3DXVECTOR3;
	m_nLife = 1;
	m_bDead = false;
}

//==================================================================================
// デストラクタ
//==================================================================================
CEffect::~CEffect()
{

}

//==================================================================================
// 生成
//==================================================================================
CEffect* CEffect::Create(D3DXVECTOR3 pos, D3DXVECTOR3 move,float fWidth, float fHeight, D3DXCOLOR col, int nLife, int texadress)
{
	// インスタンス生成
	CEffect* pEffect = new CEffect;

	// 初期化
	pEffect->Init(pos, move, fWidth, fHeight, col, nLife, texadress);

	// ポインタを返す
	return pEffect;
}

//==================================================================================
// 初期化
//==================================================================================
HRESULT CEffect::Init(D3DXVECTOR3 pos, D3DXVECTOR3 move, float fWidth, float fHeight, D3DXCOLOR col, int nLife, int texadress)
{
	// ビルボードクラスの初期化
	CBillboard::Init(pos, fWidth, fHeight, texadress);

	// 色を設定
	D3DXCOLOR* pcol = GetColor();
	*pcol = col;
	SetColor(*pcol);

	// エフェクトの値を設定
	m_move = move;				// 移動量
	m_nLife = nLife;		// 寿命

	return S_OK;
}

//==================================================================================
// 終了
//==================================================================================
void CEffect::Uninit(void)
{
	// ビルボードクラスの終了処理
	CBillboard::Uninit();
}

//==================================================================================
// 更新
//==================================================================================
void CEffect::Update(void)
{
	// 位置更新
	D3DXVECTOR3* pos = GetPosition();		// ビルボードの座標取得
	*pos += m_move;							// 移動量分更新

	// 寿命を削る
	m_nLife--;

	// 寿命0でフラグを立てる
	if (m_nLife <= 0)
	{
		m_bDead = true;
	}
}

//==================================================================================
// 描画
//==================================================================================
void CEffect::Draw(void)
{
	// ビルボードクラスの描画処理
	CBillboard::Draw();
}