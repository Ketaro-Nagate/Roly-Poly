//==================================================================================
// マネージャーからプレイヤーを取得
//==================================================================================
CPlayer* CEnemy::GetPlayer(void)
{
	CManager* pManager = CManager::GetManager();				// マネージャへのポインタ
	CGame* pGame = dynamic_cast<CGame*>(pManager->GetScene());	// ゲームシーンへのポインタ
	CPlayer* pPlayer = pGame->GetPlayer();						// プレイヤーへのポインタ

	// プレイヤーへのポインタを返す
	return pPlayer;
}