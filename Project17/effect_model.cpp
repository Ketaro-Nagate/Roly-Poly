//**********************************************************************************
// マクロ定義
//**********************************************************************************
#define GRAVITY (2.0f)			// 重力

//==================================================================================
// コンストラクタ
//==================================================================================
CModelEffect::CModelEffect()
{
	m_move = NULL_D3DXVECTOR3;
	m_rotvalue = NULL_D3DXVECTOR3;
	m_nLife = 1;
	m_bDead = false;
	m_ModelScale = 2.0f;
}

//==================================================================================
// デストラクタ
//==================================================================================
CModelEffect::~CModelEffect()
{

}

//==================================================================================
// 生成
//==================================================================================
CModelEffect* CModelEffect::Create(D3DXVECTOR3 pos, D3DXVECTOR3 rot, D3DXVECTOR3 move, D3DXVECTOR3 rotValue, int nLife, const char* pFileName)
{
	// インスタンス生成
	CModelEffect* pEffect = new CModelEffect;

	// 初期化
	pEffect->Init(pos, rot, move, rotValue, nLife, pFileName);

	// ポインタを返す
	return pEffect;
}

//==================================================================================
// 初期化
//==================================================================================
HRESULT CModelEffect::Init(D3DXVECTOR3 pos, D3DXVECTOR3 rot, D3DXVECTOR3 move, D3DXVECTOR3 rotValue, int nLife,const char* pFileName)
{
	// モデルクラスの初期化
	CObjectX::Init(pos, rot, pFileName);

	// モデルエフェクトの値を設定
	m_move = move;
	m_rotvalue = rotValue;
	m_nLife = nLife;

	return S_OK;
}

//==================================================================================
// 終了
//==================================================================================
void CModelEffect::Uninit(void)
{
	// モデルクラスの終了処理
	CObjectX::Uninit();
}

//==================================================================================
// 更新
//==================================================================================
void CModelEffect::Update(void)
{
	// 位置更新
	D3DXVECTOR3* pos = GetPosition();		// モデルの座標取得
	*pos += m_move;							// 移動量分更新
	pos->y -= GRAVITY;

	// 角度更新
	D3DXVECTOR3* rot = GetRotation();
	*rot += m_rotvalue;

	// 寿命を削る
	m_nLife--;

	m_ModelScale -= 0.02f;

	// 寿命0でフラグを立てる
	if (m_nLife <= 0 || m_ModelScale <= 0.0f)
	{
		m_bDead = true;
	}
}

